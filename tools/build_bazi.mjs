import { build } from 'esbuild';

// Both the service and the file:// bridge use exactly the same pattern rules.
for (const [entry, outfile] of [
  ['src/bazi/ui/baziApp.js', 'bazi_app.js'],
  ['src/bazi/ui/patternBridge.js', 'bazi_patterns.js']
]) {
  await build({ entryPoints:[entry], outfile, bundle:true, platform:'browser', format:'iife',
    minify:true, legalComments:'eof', banner:{js:'/* Generated by tools/build_bazi.mjs. */'} });
}
