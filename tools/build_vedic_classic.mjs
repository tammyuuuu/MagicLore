import fs from 'node:fs';
import path from 'node:path';

const root=process.cwd(),entry=path.resolve(root,'src/vedic/ui/vedicApp.js'),modules=new Map();
const normalize=file=>path.relative(root,file).replaceAll('\\','/');
function bundle(file){
  file=path.resolve(file);if(modules.has(file))return normalize(file);
  let source=fs.readFileSync(file,'utf8'),exports=[];
  source=source.replace(/import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"]\s*;?/g,(_,names,specifier)=>{
    if(specifier.includes('astronomy-engine'))return `const {${names}}=globalThis.Astronomy;`;
    const dependency=path.resolve(path.dirname(file),specifier);bundle(dependency);return `const {${names}}=__require(${JSON.stringify(normalize(dependency))});`;
  });
  source=source.replace(/export\s+(const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/g,(_,kind,name)=>{exports.push(name);return `${kind} ${name}`;});
  const id=normalize(file);modules.set(file,{id,source,exports});return id;
}
const entryId=bundle(entry),definitions=[...modules.values()].map(module=>`__define(${JSON.stringify(module.id)},function(exports,__require){\n${module.source}\nObject.assign(exports,{${module.exports.join(',')}});\n});`).join('\n');
const output=`/* Generated by tools/build_vedic_classic.mjs. Do not edit directly. */\n(function(){\n'use strict';\nconst __factories=Object.create(null),__cache=Object.create(null);\nfunction __define(id,factory){__factories[id]=factory;}\nfunction __require(id){if(__cache[id])return __cache[id];const exports={};__cache[id]=exports;if(!__factories[id])throw new Error('Missing bundled module: '+id);__factories[id](exports,__require);return exports;}\n${definitions}\n__require(${JSON.stringify(entryId)});\n})();\n`;
fs.writeFileSync(path.resolve(root,'vedic_formal_app.js'),output);
console.log(`Built vedic_formal_app.js from ${modules.size} local modules.`);

